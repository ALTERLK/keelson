"""Regenerate bench report tables from run artifacts.

Two modes:

  * default (no --set): auto-discovers the latest run per canonical arm under
    bench/runs/ (raw_api / no_skill / skill_v1 / skill_evolved) — same as
    before, for the steady-state 4-arm table.
  * --set LABEL=dir[,dir...] (repeatable): compare arbitrary named series, each
    backed by one or more run dirs (multiple = --repeats runs to pool). Use
    this for a before/after comparison where both sides share an `arm` name
    (e.g. a worktree at an older commit) and can't be told apart by arm alone.

Repeat-aware: when a series has >1 row per task_id (from --repeats or from
multiple run dirs), accuracy and the paired comparison use the per-task mean
hit rate (keelson.bench.metrics.pooled_arm_accuracy /
paired_bootstrap_delta_pooled), not raw-row counts.

Prints to stdout; paste into bench/REPORT.md (prose is written by hand). Cost
is NOT computed here — the provider dashboard is authoritative.

Run:
  python scripts/bench_report.py
  python scripts/bench_report.py --set before=bench/runs/2026...-no_skill \
                                  --set after=bench/runs/2026...-no_skill,bench/runs/2026...-no_skill
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_ROOT))

from keelson.bench import metrics  # noqa: E402

ARMS = ("raw_api", "no_skill", "skill_v1", "skill_evolved")


def _latest_run_per_arm(runs_dir: Path) -> dict[str, Path]:
    best: dict[str, tuple[str, Path]] = {}
    for d in runs_dir.iterdir():
        if not (d / "results.jsonl").is_file():
            continue
        cfg_path = d / "config.json"
        arm = ""
        if cfg_path.is_file():
            arm = json.loads(cfg_path.read_text(encoding="utf-8")).get("arm", "")
        arm = arm or d.name.split("-", 1)[-1]
        if arm not in ARMS:
            continue
        key = d.name  # timestamped, lexicographically sortable
        if arm not in best or key > best[arm][0]:
            best[arm] = (key, d)
    return {a: p for a, (_, p) in best.items()}


def _load(run_dir: Path) -> list[dict]:
    with (run_dir / "results.jsonl").open(encoding="utf-8") as f:
        return [json.loads(ln) for ln in f if ln.strip()]


def _parse_sets(raw: list[str]) -> dict[str, list[Path]]:
    out: dict[str, list[Path]] = {}
    for spec in raw:
        label, _, dirs = spec.partition("=")
        if not label or not dirs:
            raise SystemExit(f"--set must be LABEL=dir[,dir...], got: {spec!r}")
        out[label] = [Path(d) for d in dirs.split(",")]
    return out


def main() -> int:
    for _stream in (sys.stdout, sys.stderr):
        try:
            _stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass

    ap = argparse.ArgumentParser()
    ap.add_argument("--set", dest="sets", action="append", default=[],
                    help="LABEL=dir[,dir...] — repeatable, e.g. --set before=bench/runs/X")
    ap.add_argument("--pairs", default="",
                    help="comma-separated A-B pairs to compare, e.g. after-before,after-raw_api "
                         "(default: every ordered pair among the series)")
    args = ap.parse_args()

    if args.sets:
        label_dirs = _parse_sets(args.sets)
        order = list(label_dirs.keys())
        data = {label: [row for d in dirs for row in _load(d)] for label, dirs in label_dirs.items()}
        srcs = {label: ", ".join(d.name for d in dirs) for label, dirs in label_dirs.items()}
    else:
        runs_dir = _ROOT / "bench" / "runs"
        latest = _latest_run_per_arm(runs_dir)
        if not latest:
            print("no runs found under bench/runs/ (or pass --set)", file=sys.stderr)
            return 1
        order = [a for a in ARMS if a in latest]
        data = {a: _load(latest[a]) for a in order}
        srcs = {a: latest[a].name for a in order}

    if args.pairs:
        pairs = [tuple(p.split("-", 1)) for p in args.pairs.split(",")]
    else:
        pairs = [(a, b) for i, a in enumerate(order) for b in order[i + 1:]]

    print("<!-- generated by scripts/bench_report.py -->\n")
    for label in order:
        n_dirs = len(label_dirs[label]) if args.sets else 1
        print(f"* `{label}`  <- {srcs[label]}" + (f"  ({n_dirs} run dirs pooled)" if n_dirs > 1 else ""))
    print()

    # ---- per-series summary (repeat-aware) ----
    print("## Per-series summary\n")
    print("| series | n rows | n tasks | accuracy | task-mean range | unstable tasks | "
          "avg model_calls | hit_cap rate | invalid-tool rate |")
    print("|--------|-------:|--------:|---------:|:----------------:|---------------:|"
          "----------------:|-------------:|-------------------:|")
    for label in order:
        rows = data[label]
        s = metrics.summarize_arm(label, rows)
        p = metrics.pooled_arm_accuracy(rows)
        avg_mc = sum(r.get("model_calls", 0) for r in rows) / max(1, len(rows))
        cap_rate = sum(1 for r in rows if r.get("hit_cap")) / max(1, len(rows))
        rng = f"[{p.get('task_mean_min', 0):.0%}, {p.get('task_mean_max', 0):.0%}]" if p["n_tasks"] else "-"
        print(f"| `{label}` | {p['n_rows']} | {p['n_tasks']} | {p['accuracy']:.0%} | {rng} | "
              f"{p.get('tasks_unstable', 0)} | {avg_mc:.1f} | {cap_rate:.0%} | {s.invalid_tool_call_rate:.0%} |")
    print()

    # ---- paired (repeat-aware pooled bootstrap) ----
    print("## Paired comparison (per-task mean hit rate, 10 000-iter cluster bootstrap)\n")
    print("| A − B | n tasks | Δ accuracy | 95% CI | significant? |")
    print("|-------|--------:|-----------:|:------:|:------------:|")
    for a, b in pairs:
        if a not in data or b not in data:
            continue
        bs = metrics.paired_bootstrap_delta_pooled(data[a], data[b], iters=10_000, seed=0)
        if bs["n"] == 0:
            continue
        sig = "**yes**" if bs["significant"] else "no"
        print(f"| `{a}` − `{b}` | {bs['n']} | {bs['delta']:+.0%} | "
              f"[{bs['ci_low']:+.0%}, {bs['ci_high']:+.0%}] | {sig} |")
    print()

    # ---- hop depth on common tasks ----
    common = set.intersection(*[{r["task_id"] for r in data[a]} for a in order]) if order else set()
    if common:
        print(f"## Accuracy by hop depth (common tasks, n={len(common)})\n")
        print("| hops | " + " | ".join(f"`{a}`" for a in order) + " | n |")
        print("|-----:|" + "|".join(["--:"] * len(order)) + "|--:|")
        by_depth: dict[int, dict[str, list[int]]] = {}
        for arm in order:
            for r in data[arm]:
                if r["task_id"] not in common:
                    continue
                h = r.get("hops")
                by_depth.setdefault(h, {}).setdefault(arm, []).append(1 if r.get("correct") else 0)
        for h in sorted(k for k in by_depth if k is not None):
            row = [f"{h}"]
            n_h = 0
            for arm in order:
                v = by_depth[h].get(arm, [])
                n_h = max(n_h, len(v))
                row.append(f"{sum(v)}/{len(v)}" if v else "-")
            row.append(str(n_h))
            print("| " + " | ".join(row) + " |")
        print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
