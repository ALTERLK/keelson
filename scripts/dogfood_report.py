"""The table in docs/dogfooding.md, from the records in bench/dogfood/.

Each real task done with Keelson leaves ``bench/dogfood/<n>.json``: the request, what `keelson -p
--output-format json` printed (verification, usage), counts of the permission decisions and undo events
seen on the event bus, the wall time, and what happened to the change afterwards (kept, kept with edits,
dropped) with a note. ``--ingest`` builds such a record from a raw run (the -p output, its stderr/meta and
an events log), with local paths replaced, so nothing personal is committed.

    python scripts/dogfood_report.py                      # rewrite the table in docs/dogfooding.md
    python scripts/dogfood_report.py --ingest N RAW_DIR --request "..." --outcome kept --note "..."
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECORDS = ROOT / "bench" / "dogfood"
DOC = ROOT / "docs" / "dogfooding.md"
OUTCOMES = {"kept": "原样留下", "kept-edited": "改过再留", "dropped": "丢掉"}
BEGIN, END = "<!-- dogfood:begin (generated by scripts/dogfood_report.py) -->", "<!-- dogfood:end -->"


def _redact(text: str) -> str:
    text = re.sub(r"[A-Za-z]:[\\/]+Users[\\/]+[^\\/\s\"']+", "~", text)
    return re.sub(r"/(?:home|Users)/[^/\s\"']+", "~", text)


def ingest(n: int, raw: Path, request: str, outcome: str, note: str) -> Path:
    answer = json.loads((raw / f"{n}.json").read_text(encoding="utf-8"))
    meta = (raw / f"{n}.meta").read_text(encoding="utf-8")
    seconds = int(re.search(r"seconds=(\d+)", meta).group(1))
    perms: Counter = Counter()
    undo = scope = folds = 0
    events_file = raw / f"{n}.events.jsonl"
    if events_file.is_file():
        for line in events_file.read_text(encoding="utf-8").splitlines():
            event = json.loads(line)
            kind, data = event["type"], event.get("data", {})
            if kind == "permission" and not data.get("speculative"):
                perms[data.get("action", "?")] += 1
            undo += kind == "undo"
            scope += kind == "scope"
            folds += kind == "context_fold"
    verify = answer.get("verify") or {}
    record = {
        "n": n, "request": request, "model": answer.get("model"), "seconds": seconds,
        "verify": {k: verify.get(k) for k in ("status", "detail", "weakened", "unproven", "out_of_scope", "changed")},
        "usage": answer.get("usage"), "error": answer.get("error"),
        "events_logged": events_file.is_file(),
        "permissions": dict(perms), "undo_events": undo, "scope_events": scope, "folds": folds,
        "outcome": outcome, "note": note,
        "answer_tail": (answer.get("result") or "")[-800:],
    }
    RECORDS.mkdir(parents=True, exist_ok=True)
    path = RECORDS / f"{n:02d}.json"
    path.write_text(_redact(json.dumps(record, ensure_ascii=False, indent=2)) + "\n", encoding="utf-8", newline="\n")
    diff = raw / f"{n}.diff"
    if diff.is_file():
        (RECORDS / f"{n:02d}.diff").write_text(_redact(diff.read_text(encoding="utf-8")), encoding="utf-8",
                                               newline="\n")
    return path


def load() -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted(RECORDS.glob("*.json"))]


def build(records: list[dict]) -> str:
    rows = ["| # | 请求 | 验证结论 | 花费 | 缓存命中 | 耗时 | 拒绝 / 询问 | 结果 |",
            "|---|---|---|---|---|---|---|---|"]
    total_in = total_hit = 0
    total_usd = 0.0
    for r in records:
        u = r.get("usage") or {}
        total_in += u.get("input_tokens", 0)
        total_hit += u.get("cache_hit_tokens", 0)
        total_usd += u.get("cost_usd", 0.0)
        hit = f"{u['cache_hit_tokens'] / u['input_tokens']:.0%}" if u.get("input_tokens") else "–"
        verdict = r["verify"].get("status") or "–"
        if r["verify"].get("weakened"):
            verdict += "（标记：测试被削弱）"
        perms = r.get("permissions") or {}
        gate = f"{perms.get('deny', 0)} / {perms.get('confirm', 0)}" if r.get("events_logged") else "未记录"
        rows.append(f"| [{r['n']}](../bench/dogfood/{r['n']:02d}.json) | {r['request']} | {verdict} | "
                    f"${u.get('cost_usd', 0):.4f} | {hit} | {r['seconds']} 秒 | {gate} | {OUTCOMES.get(r['outcome'], r['outcome'])} |")
    kept = sum(1 for r in records if r["outcome"].startswith("kept"))
    edited = sum(1 for r in records if r["outcome"] == "kept-edited")
    summary = (f"\n\n共 {len(records)} 个任务，留下 {kept} 个（其中 {edited} 个我改过再留）；合计 ${total_usd:.3f}；"
               f"输入 token 的缓存命中率 {(total_hit / total_in if total_in else 0):.0%}。")
    notes = "\n".join(f"- **{r['n']}.** {r['note']}" for r in records if r.get("note"))
    return BEGIN + "\n" + "\n".join(rows) + summary + ("\n\n" + notes if notes else "") + "\n" + END


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--ingest", nargs=2, metavar=("N", "RAW_DIR"))
    ap.add_argument("--request", default="")
    ap.add_argument("--outcome", default="kept")
    ap.add_argument("--note", default="")
    args = ap.parse_args(argv)
    if args.ingest:
        print(ingest(int(args.ingest[0]), Path(args.ingest[1]), args.request, args.outcome, args.note))
    text = DOC.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print(f"{DOC} has no generated block", file=sys.stderr)
        return 2
    DOC.write_text(text[:text.index(BEGIN)] + build(load()) + text[text.index(END) + len(END):], encoding="utf-8",
                   newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
