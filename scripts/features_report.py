"""Tables for bench/FEATURES.md, computed from the raw feature-experiment results.

Reads the run folders listed in bench/features_runs.json (else the newest
``bench/runs/*-features-<experiment>-*`` for each experiment), pools their results.jsonl, and rewrites the part of bench/FEATURES.md between the generated-block markers.
Every number in that block comes from those files; the run folder of each table is printed under it.

    python scripts/features_report.py            # rewrite the block
    python scripts/features_report.py --check    # exit 1 if the block is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "bench" / "runs"
REPORT = ROOT / "bench" / "FEATURES.md"
MANIFEST = ROOT / "bench" / "features_runs.json"   # which runs the report uses
BEGIN, END = "<!-- features:begin (generated by scripts/features_report.py) -->", "<!-- features:end -->"
EXPERIMENTS = ("verify", "scope", "ledger", "undo", "danger")


def latest(experiment: str) -> Path | None:
    found = sorted(p for p in RUNS.glob(f"*-features-{experiment}-*") if (p / "results.jsonl").is_file())
    return found[-1] if found else None


def load(run: Path) -> list[dict]:
    return [json.loads(line) for line in (run / "results.jsonl").read_text(encoding="utf-8").splitlines() if line]


def pct(num: int, den: int) -> str:
    return f"{num}/{den} ({num / den:.0%})" if den else "–"


def money(rows: list[dict]) -> str:
    return f"${sum(r.get('cost_usd', 0) for r in rows):.3f}"


def cache(rows: list[dict]) -> str:
    total = sum(r.get("input_tokens", 0) for r in rows)
    hit = sum(r.get("cache_hit_tokens", 0) for r in rows)
    return f"{hit / total:.0%}" if total else "–"


def table(head: list[str], body: list[list]) -> str:
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in body]
    return "\n".join(lines)


def by_arm(rows: list[dict]) -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = {}
    for r in rows:
        out.setdefault(r.get("arm", "-"), []).append(r)
    return dict(sorted(out.items()))


def ok_rows(rows: list[dict]) -> list[dict]:
    """Rows that were graded (an exception before grading leaves only an error)."""
    return [r for r in rows if any(k in r for k in ("tests_pass", "check_pass", "rules", "undo_ok"))]


def section_verify(rows: list[dict]) -> str:
    kinds = sorted({r.get("kind", "spec") for r in rows})
    parts = []
    for kind in kinds:
        subset = [r for r in rows if r.get("kind", "spec") == kind]
        label = {"spec": "Fix or implement one function (edge cases in the docstring and tests)",
                 "regression": "The obvious fix breaks another module's tests"}.get(kind, kind)
        parts.append(f"**{label}** ({len({r['task_id'] for r in subset})} tasks)\n\n" + _verify_table(subset))
    return "\n\n".join(parts)


def _verify_table(rows: list[dict]) -> str:
    body = []
    for arm, group in by_arm(rows).items():
        g = ok_rows(group)
        failed = [r for r in g if not r["tests_pass"]]
        broke = sum(1 for r in g if r.get("check_pass") and r.get("suite_pass") is False)
        body.append([
            f"verification {arm}", len(group), pct(sum(r["tests_pass"] for r in g), len(g)), broke,
            pct(sum(r["false_success"] for r in g), len(g)),
            f"{sum(1 for r in failed if not r['false_success'])}/{len(failed)}",
            pct(sum(1 for r in g if r.get("model_test_runs")), len(g)),
            " / ".join(f"{k} {sum(1 for r in g if r.get('outcome') == k)}" for k in ("passed", "failed", "unverified"))
            if arm == "on" else "–",
            money(group), cache(group),
        ])
    head = ["arm", "runs", "done and all tests pass", "request done, another test broken", "false success",
            "failures admitted", "model ran tests itself",
            "Keelson's verdict", "cost", "cache hits"]
    tasks = sorted({r["task_id"] for r in rows})
    per_task = [[t] + [pct(sum(r["tests_pass"] for r in ok_rows(g) if r["task_id"] == t),
                           sum(1 for r in ok_rows(g) if r["task_id"] == t)) for g in by_arm(rows).values()]
                for t in tasks]
    return table(head, body) + "\n\nPer task (tests pass):\n\n" + table(["task", *by_arm(rows)], per_task)


def section_scope(rows: list[dict]) -> str:
    body = []
    for arm, group in by_arm(rows).items():
        g = ok_rows(group)
        body.append([
            f"scope guard {arm}", len(group), pct(sum(r["check_pass"] for r in g), len(g)),
            pct(sum(1 for r in g if r["out_of_scope_changed"]), len(g)),
            sum(len(r["out_of_scope_changed"]) for r in g),
            sum(len(r["out_of_scope_asks_denied"]) for r in g),
            pct(sum(1 for r in g if r["new_files"]), len(g)), money(group), cache(group),
        ])
    head = ["arm", "runs", "request done (held-back check)", "runs that changed other files",
            "other files changed", "out-of-scope asks (answered no)", "runs that added files", "cost", "cache hits"]
    changed = sorted({f"{r['task_id']}: {', '.join(r['out_of_scope_changed'])} ({r['arm']})"
                      for r in ok_rows(rows) if r["out_of_scope_changed"]})
    tail = ("\n\nOther files changed: " + "; ".join(changed)) if changed else "\n\nNo run changed another file."
    return table(head, body) + tail


def section_ledger(rows: list[dict]) -> str:
    body = []
    rule_names = sorted({k for r in ok_rows(rows) for k in r["rules"]})
    for arm, group in by_arm(rows).items():
        g = ok_rows(group)
        body.append([f"ledger {arm}", len(group),
                     pct(sum(r["rules_kept"] for r in g), sum(r["rules_total"] for r in g)),
                     pct(sum(1 for r in g if r["rules_kept"] == r["rules_total"]), len(g)),
                     pct(sum(r["task_done"] for r in g), len(g)), money(group), cache(group)])
    head = ["arm", "runs", "rules kept after the fold", "runs with every rule kept", "task done", "cost",
            "cache hits"]
    per_rule = [[name] + [pct(sum(1 for r in ok_rows(g) if r["rules"].get(name)),
                              sum(1 for r in ok_rows(g) if name in r["rules"])) for g in by_arm(rows).values()]
                for name in rule_names]
    captured = sorted({c for r in ok_rows(rows) for c in r.get("ledger_constraints", [])})
    return (table(head, body) + "\n\nPer rule:\n\n" + table(["rule", *by_arm(rows)], per_rule)
            + "\n\nSentences the ledger kept word for word (both arms record them; only the `on` arm puts them back "
              "after the fold):\n\n" + "\n".join(f"- {c}" for c in captured))


def section_undo(rows: list[dict]) -> str:
    g = ok_rows(rows)
    changed = sum(r["files_changed"] for r in g)
    body = [[len(rows), sum(1 for r in g if r["checkpoint_mode"] == "git"),
             sum(r["shell_calls"] for r in g), sum(r["delete_calls"] for r in g), changed,
             pct(sum(1 for r in g if r["identical_after_undo"]), len(g)),
             pct(sum(r["edit_tools_only_would_restore"] for r in g), changed), money(rows), cache(rows)]]
    head = ["runs", "git checkpoints", "shell calls", "delete_files calls", "files changed",
            "byte-identical after one /undo", "files an edit-tools-only undo would restore", "cost", "cache hits"]
    return table(head, body)


def section_danger(rows: list[dict]) -> str:
    modes = ("default", "acceptEdits", "dontAsk", "bypassPermissions")
    body = []
    for kind in ("catastrophic", "risky", "everyday-delete", "everyday"):
        group = [r for r in rows if r["kind"] == kind]
        if not group:
            continue
        cells = []
        for m in modes:
            counts = {a: sum(1 for r in group if r[m] == a) for a in ("deny", "confirm", "allow")}
            cells.append(" / ".join(f"{a} {n}" for a, n in counts.items() if n))
        body.append([kind, len(group), *cells])
    slips = [r for r in rows if r["kind"] == "catastrophic" and r["bypassPermissions"] != "deny"]
    tail = "\n\nCatastrophic commands not refused outright (asked in the other modes, run in bypassPermissions):\n\n"
    tail += "\n".join(f"- `{r['command']}` (default: {r['default']})" for r in slips) if slips else "- none"
    return table(["kind", "commands", *modes], body) + tail


SECTIONS = {"verify": ("Verified completion", section_verify), "scope": ("Scope guard", section_scope),
            "ledger": ("Task ledger across a fold", section_ledger), "undo": ("Undo after shell changes", section_undo),
            "danger": ("Destructive commands (no model)", section_danger)}


def build(runs: dict[str, list[Path]]) -> str:
    parts = [BEGIN]
    for exp in EXPERIMENTS:
        folders = runs.get(exp) or []
        if not folders:
            continue
        title, fn = SECTIONS[exp]
        rows = [row for run in folders for row in load(run)]
        sources = []
        for run in folders:
            config = json.loads((run / "config.json").read_text(encoding="utf-8")) \
                if (run / "config.json").is_file() else {}
            what = f"model `{config['model']}`, {config.get('repeats', 1)} repeats" if config.get("model") \
                else "no model"
            sources.append(f"`bench/runs/{run.name}/results.jsonl` ({what}, commit `{config.get('git_commit', '?')}`)")
        parts += [f"### {title}", "", fn(rows), "", "<sub>Raw results: " + "; ".join(sources) + ".</sub>", ""]
    parts.append(END)
    return "\n".join(parts)


def chosen_runs() -> dict[str, list[Path]]:
    """The run folders listed in bench/features_runs.json; the newest one for an experiment not listed."""
    listed = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.is_file() else {}
    runs: dict[str, list[Path]] = {}
    for exp in EXPERIMENTS:
        if listed.get(exp):
            runs[exp] = [RUNS / name for name in listed[exp]]
        elif (run := latest(exp)) is not None:
            runs[exp] = [run]
    return runs


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    block = build(chosen_runs())
    text = REPORT.read_text(encoding="utf-8") if REPORT.is_file() else f"# Feature experiments\n\n{BEGIN}\n{END}\n"
    if BEGIN not in text or END not in text:
        print(f"{REPORT} has no generated block", file=sys.stderr)
        return 2
    new = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    if args.check:
        return 0 if new == text else 1
    REPORT.write_text(new, encoding="utf-8", newline="\n")
    print(block)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
