"""Build the Windows desktop app: dist/Keelson/{Keelson.exe, keelson-cli.exe}.

    pip install -e ".[desktop,build]"
    python scripts/build_desktop.py            # build, check, and zip
    python scripts/build_desktop.py --no-zip   # build and check only

Both executables share one ``_internal`` folder (one PyInstaller spec, one COLLECT):

* ``Keelson.exe`` is the windowed app. It also runs each project's console server
  (``Keelson.exe --console-server ...``), so no console window ever appears.
* ``keelson-cli.exe`` is the console build of the ``keelson`` command.

The console's own data (benchmark results, the case study, the skill-evolution
demo and the demo traces) is copied in the repository's layout under
``_internal``: ``keelson/web/data.py`` finds it two levels above itself, exactly
as it does in a git checkout. Nothing here uploads or publishes anything.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist"
WORK = ROOT / "build" / "pyinstaller"
APP = DIST / "Keelson"


def data_files() -> list[tuple[str, str]]:
    """(source, folder inside the bundle) pairs: the static console plus the data it shows."""
    pairs = [(str(ROOT / "keelson" / "web" / "static"), "keelson/web/static")]
    bench = ROOT / "bench"
    if (bench / "dashboard.json").is_file():
        pairs.append((str(bench / "dashboard.json"), "bench"))
    for results in sorted((bench / "runs").glob("*/results.jsonl")):
        pairs.append((str(results), f"bench/runs/{results.parent.name}"))
    if (bench / "casestudy" / "results.json").is_file():
        pairs.append((str(bench / "casestudy" / "results.json"), "bench/casestudy"))
    for folder in ("docs/self-evolution-demo", "demo/traces"):
        if (ROOT / folder).is_dir():
            pairs.append((str(ROOT / folder), folder))
    return pairs


SPEC = """\
# Generated by scripts/build_desktop.py; edit that file instead.
from PyInstaller.utils.hooks import collect_submodules

ROOT = {root!r}
datas = {datas!r}
hidden = (collect_submodules("keelson") + collect_submodules("uvicorn")
          + ["webview.platforms.edgechromium", "webview.platforms.winforms"])
# PIL only arrives through pygments' image formatter (rich -> pygments); nothing here renders images.
excludes = ["tkinter", "pytest", "_pytest", "IPython", "matplotlib", "numpy", "PIL"]


def analysis(script):
    return Analysis([ROOT + "/scripts/" + script], pathex=[ROOT], datas=datas, hiddenimports=hidden,
                    excludes=excludes, noarchive=False)


window = analysis("keelson_desktop.py")
cli = analysis("keelson_cli.py")

window_exe = EXE(PYZ(window.pure), window.scripts, [], exclude_binaries=True, name="Keelson",
                 console=False, upx=False)
cli_exe = EXE(PYZ(cli.pure), cli.scripts, [], exclude_binaries=True, name="keelson-cli",
              console=True, upx=False)

COLLECT(window_exe, window.binaries, window.datas, cli_exe, cli.binaries, cli.datas,
        name="Keelson", upx=False)
"""


def build() -> None:
    try:
        import PyInstaller  # noqa: F401
        import webview  # noqa: F401
    except ImportError:
        sys.exit('Missing build tools. Install them with:  pip install -e ".[desktop,build]"')
    WORK.mkdir(parents=True, exist_ok=True)
    spec = WORK / "keelson.spec"
    spec.write_text(SPEC.format(root=ROOT.as_posix(), datas=data_files()), encoding="utf-8", newline="\n")
    subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
                    "--distpath", str(DIST), "--workpath", str(WORK), str(spec)], check=True, cwd=ROOT)


def check() -> None:
    """Fail loudly if the bundle is missing a piece the app needs at run time."""
    internal = APP / "_internal"
    needed = [
        APP / "Keelson.exe",
        APP / "keelson-cli.exe",
        internal / "keelson" / "web" / "static" / "index.html",
        internal / "keelson" / "web" / "static" / "desktop.html",
        internal / "bench" / "dashboard.json",
        internal / "demo" / "traces",
    ]
    missing = [str(p.relative_to(DIST)) for p in needed if not p.exists()]
    if missing:
        sys.exit("Build is incomplete; missing: " + ", ".join(missing))
    result = subprocess.run([str(APP / "keelson-cli.exe"), "--help"], capture_output=True, timeout=120)
    if result.returncode != 0:
        sys.exit("keelson-cli.exe --help failed:\n" + result.stderr.decode("utf-8", "replace"))
    size = sum(p.stat().st_size for p in APP.rglob("*") if p.is_file())
    print(f"ok: {APP}  ({size / 1e6:.0f} MB)")


def make_zip() -> Path:
    sys.path.insert(0, str(ROOT))
    from keelson import __version__

    archive = DIST / f"Keelson-{__version__}-windows-x64.zip"
    archive.unlink(missing_ok=True)
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for path in sorted(APP.rglob("*")):
            if path.is_file():
                zf.write(path, Path("Keelson") / path.relative_to(APP))
    print(f"zip: {archive}  ({archive.stat().st_size / 1e6:.0f} MB)")
    return archive


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--no-zip", action="store_true", help="skip the zip archive")
    args = parser.parse_args()
    if sys.platform != "win32":
        sys.exit("The desktop build is Windows-only for now.")
    if APP.exists():
        shutil.rmtree(APP)
    build()
    check()
    if not args.no_zip:
        make_zip()


if __name__ == "__main__":
    main()
