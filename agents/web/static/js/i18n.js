const listeners = new Set();
let lang = "en";

try {
  lang = (navigator.language || "en").toLowerCase().startsWith("zh") ? "zh" : "en";
  const saved = localStorage.getItem("keelson-lang");
  if (saved === "en" || saved === "zh") lang = saved;
} catch { /* storage unavailable: keep the default */ }

export function t(key) {
  return dict[lang][key] ?? dict.en[key] ?? key;
}

export function getLang() { return lang; }

export function setLang(next) {
  lang = next;
  try { localStorage.setItem("keelson-lang", next); } catch { /* ignore */ }
  document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
  applyStatic();
  for (const fn of listeners) fn();
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

// Fill elements that carry a data-i18n key (the static shell in index.html).
export function applyStatic(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
}
